# ---------- дедупликация против всей существующей вселенной
existing=set()
for r in csv.DictReader(open(os.path.join(BASE,'100_INITIAL_DIRECTIONS.csv'),encoding='utf-8'),delimiter=';'):
    existing.add(r['nisha'].lower())
for r in csv.DictReader(open(os.path.join(BASE,'PETS_RETAIL_EXPANSION.csv'),encoding='utf-8'),delimiter=';'):
    existing.add(r['nisha'].lower())
dupes=[k for k,v in D.items() if v[1].lower() in existing]
assert not dupes, f"дубликаты названий: {dupes}"

rows=[]
for eid,(dom,name,client,check,why,flt,vals,yf,note) in D.items():
    if flt:
        rows.append(dict(id=eid,domain=dom,nisha=name,tip_klienta=client,chek=check,opisanie=why,
                         status="ОТСЕЯНА",kod=flt[0],prichina=flt[1],score="",yf="",kommentariy="",
                         **{k:"" for k in O}))
    else:
        raw=sum(vals[i]*W[k] for i,k in enumerate(O))
        pen=sum(YF[f] for f in yf)
        rows.append(dict(id=eid,domain=dom,nisha=name,tip_klienta=client,chek=check,opisanie=why,
                         status="ПРОШЛА",kod="",prichina="",score=round(raw-pen,2),
                         yf=",".join(yf),kommentariy=note,
                         **{k:vals[i] for i,k in enumerate(O)}))

fields=["id","domain","nisha","tip_klienta","chek","opisanie","status","kod","prichina","score","yf"]+O+["kommentariy"]
with open(os.path.join(BASE,'THIN_DOMAINS_EXPANSION.csv'),'w',encoding='utf-8',newline='') as f:
    w=csv.DictWriter(f,fieldnames=fields,delimiter=';');w.writeheader()
    for r in rows: w.writerow(r)

