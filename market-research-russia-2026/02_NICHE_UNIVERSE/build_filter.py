src = os.path.join(BASE, "100_INITIAL_DIRECTIONS.csv")
with open(src, encoding="utf-8") as f:
    rows = list(csv.DictReader(f, delimiter=";"))

assert len(rows) == 100, len(rows)
assert len(REJECT) == 50, f"отсеяно {len(REJECT)}"
assert len(PASS_REASON) == 50, f"прошло {len(PASS_REASON)}"
assert not (set(REJECT) & set(PASS_REASON)), "ниша и прошла, и отсеяна"
assert set(REJECT) | set(PASS_REASON) == {r["id"] for r in rows}, "покрыты не все 100"

passed = [r for r in rows if r["id"] in PASS_REASON]
rejected = [r for r in rows if r["id"] in REJECT]

with open(os.path.join(BASE, "50_SELECTED_NICHES.csv"), "w", encoding="utf-8", newline="") as f:
    w = csv.writer(f, delimiter=";")
    w.writerow(["id","nisha","domain","tip_klienta","sredniy_chek_ocenka_rub","sezonnost",
                "test_bez_zakupki","prichina_prohozhdeniya_filtra"])
    for r in passed:
        w.writerow([r["id"], r["nisha"], r["domain"], r["tip_klienta"],
                    r["sredniy_chek_ocenka_rub"], r["sezonnost"],
                    r["test_bez_zakupki"], PASS_REASON[r["id"]]])

with open(os.path.join(BASE, "50_REJECTED_NICHES.csv"), "w", encoding="utf-8", newline="") as f:
    w = csv.writer(f, delimiter=";")
    w.writerow(["id","nisha","domain","kod_stop_faktora","prichina_otseva"])
    for r in rejected:
        code, why = REJECT[r["id"]]
        w.writerow([r["id"], r["nisha"], r["domain"], code, why])

from collections import Counter
print("прошли фильтр:", len(passed), "| отсеяны:", len(rejected))
print("\nПричины отсева:")
for code, n in Counter(c for c, _ in REJECT.values()).most_common():
    print(f"  {code:<10} {n}")
