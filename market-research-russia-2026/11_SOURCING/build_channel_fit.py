rows = []
for pid, (tovar, nid, buyer, vals, disc, purch, alt, why) in P.items():
    score = round(sum(vals[i] * W[k] for i, k in enumerate(ORDER)), 2)
    avito = "ДА" if score >= POROG else "НЕТ"
    rows.append(dict(id=pid, tovar=tovar, nisha=nid, pokupatel=buyer,
                     **{k: vals[i] for i, k in enumerate(ORDER)},
                     CHANNEL_FIT=score, avito_podhodit=avito,
                     gde_ishchet=disc, gde_pokupaet=purch,
                     luchshiy_kanal=("Авито" if avito == "ДА" else alt),
                     obosnovanie=why))

rows.sort(key=lambda r: -r['CHANNEL_FIT'])
FIELDS = ["id","tovar","nisha","pokupatel"] + ORDER + \
         ["CHANNEL_FIT","avito_podhodit","gde_ishchet","gde_pokupaet","luchshiy_kanal","obosnovanie"]
