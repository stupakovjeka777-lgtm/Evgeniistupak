    """Тариф ТК по РФ, ОЦЕНКА. Фрахт сублинеен весу: паллета стоит не 'вес x ставка'."""
    for lim, cost in ((10,400),(50,900),(150,2200),(500,5500)):
        if kg <= lim: return cost
    return 9000

