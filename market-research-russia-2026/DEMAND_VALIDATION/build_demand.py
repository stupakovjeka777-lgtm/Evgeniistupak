# --------------------------------------------------- классификация A/B/C/D
def classify(r):
    """
    A — спрос подтверждён, фит есть, деньги быстро.
    B — спрос подтверждён, но фита нет: хороший рынок, нужен эксперт.
    C — спрос не подтверждён (мало доказательств), но тест дёшев.
    D — спрос не подтверждён И тест недёшев. Не приоритизировать СЕЙЧАС.
    """
    d, f, c = r['DEMAND_EVIDENCE'], r['FOUNDER_FIT'], r['CASHFLOW']
    cov, al, fsc = r['EVIDENCE_COVERAGE'], r['ASSET_LIGHT'], r['FIRST_SALE_COMPLEXITY']
    strong_demand = (d >= 7.0 and cov >= 40)
    cheap_test = (al >= 6.5 and fsc <= 6.5)
    if strong_demand and f >= 6.0 and c >= 7.0:
        return "A — LAUNCH NOW"
    if strong_demand and f < 6.0:
        return "B — STRATEGIC BET"
    if cheap_test:
        return "C — EXPERIMENT"
    return "D — DO NOT PRIORITIZE"

def decide(r):
    t = r['TYPE']
    if t.startswith("A"): return "GO NOW"
    if t.startswith("B"): return "WAIT" if r['FIRST_SALE_COMPLEXITY'] > 7.0 else "GO TEST"
    if t.startswith("C"): return "GO TEST"
    return "NO GO"

for r in rows:
    r['TYPE'] = classify(r)
    r['DECISION'] = decide(r)
    # практический итог с учётом доказательств спроса
    r['FINAL_PRACTICAL'] = round(
        0.25*r['DEMAND_EVIDENCE'] + 0.20*r['FOUNDER_FIT'] + 0.20*r['CASHFLOW']
        + 0.15*r['MARKET'] + 0.10*r['ASSET_LIGHT'] + 0.10*(10-r['FIRST_SALE_COMPLEXITY']), 2)

rows.sort(key=lambda r: -r['FINAL_PRACTICAL'])

