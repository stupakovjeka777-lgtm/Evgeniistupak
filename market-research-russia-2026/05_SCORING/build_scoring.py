YF_PENALTY = {"YF-1": 1.0, "YF-2": 0.5, "YF-3": 0.5, "YF-4": 0.5}

rows = []
for nid, (name, domain, scores, yflags, note) in S.items():
    assert len(scores) == len(ORDER), nid
    raw = sum(scores[i] * WEIGHTS[k] for i, k in enumerate(ORDER))
    penalty = sum(YF_PENALTY[f] for f in yflags)
    final = round(raw - penalty, 2)
    rows.append({
        "id": nid, "nisha": name, "domain": domain,
        **{k: scores[i] for i, k in enumerate(ORDER)},
        "RAW_SCORE": round(raw, 2),
        "yellow_flags": ",".join(yflags),
        "penalty": penalty,
        "FINAL_SCORE": final,
        "kommentariy": note,
    })

rows.sort(key=lambda r: -r["FINAL_SCORE"])
for i, r in enumerate(rows, 1):
    r["rank"] = i

fields = ["rank","id","nisha","domain"] + ORDER + ["RAW_SCORE","yellow_flags","penalty","FINAL_SCORE","kommentariy"]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "NICHE_SCORING_MASTER.csv")
with open(out, "w", encoding="utf-8", newline="") as f:
    w = csv.DictWriter(f, fieldnames=fields, delimiter=";")
    w.writeheader()
    for r in rows:
        w.writerow({k: r[k] for k in fields})

print(f"ниш в скоринге: {len(rows)}")
